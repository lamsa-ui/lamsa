// Builds @lamsa-ui/icons from the owned SVGs in packages/icons/svg.
//
//   node tools/icons.mjs sync       copy the icons listed in packages/icons/icons.json
//                                   from lucide-static (ISC) into packages/icons/svg
//   node tools/icons.mjs generate   write src/data.ts and icons.css from packages/icons/svg
//
// `sync` is the only step that touches Lucide. After it the SVGs are ours, so a
// change here is a change to the library. `generate` is deterministic: same SVGs in,
// same files out.
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'packages/icons');
const svgDir = join(pkg, 'svg');

// Arrows and chevrons that point the way text runs. They flip in right-to-left pages.
const MIRRORED = [
  'arrow-left',
  'arrow-right',
  'chevron-left',
  'chevron-right',
  'chevrons-left',
  'chevrons-right',
  'log-in',
  'log-out',
  'undo-2',
  'redo-2',
  'panel-left',
  'panel-right',
  'send',
];

const sync = () => {
  const names = JSON.parse(readFileSync(join(pkg, 'icons.json'), 'utf8'));
  const source = join(root, 'node_modules/lucide-static/icons');
  mkdirSync(svgDir, { recursive: true });
  for (const file of readdirSync(svgDir)) rmSync(join(svgDir, file));
  for (const name of names) {
    const from = join(source, `${name}.svg`);
    if (!existsSync(from))
      throw new Error(`Lucide has no icon called "${name}"`);
    copyFileSync(from, join(svgDir, `${name}.svg`));
  }
  // Search words per icon, so "delete" finds the bin. Kept for the icons we ship only.
  const allTags = JSON.parse(
    readFileSync(join(root, 'node_modules/lucide-static/tags.json'), 'utf8'),
  );
  // Our own words on top of Lucide's, for icons it leaves bare or under an old name.
  const extra = JSON.parse(readFileSync(join(pkg, 'tags.extra.json'), 'utf8'));
  const tags = Object.fromEntries(
    names.map((n) => [
      n,
      [...new Set([...(extra[n] ?? []), ...(allTags[n] ?? [])])],
    ]),
  );
  writeFileSync(join(pkg, 'tags.json'), JSON.stringify(tags, null, 1) + '\n');
  copyFileSync(
    join(root, 'node_modules/lucide-static/LICENSE'),
    join(pkg, 'NOTICE'),
  );
  console.log(`Synced ${names.length} icons from lucide-static.`);
};

/** The shapes inside the <svg>, on one line. The wrapper's attributes live in the components and the CSS. */
const inner = (svg) => {
  const match = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
  if (!match) throw new Error('Not an SVG');
  return match[1].replace(/\s+/g, ' ').replace(/> </g, '><').trim();
};

const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());

const maskUrl = (shapes) => {
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${shapes}</svg>`;
  const encoded = svg
    .replace(/%/g, '%25')
    .replace(/"/g, "'")
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E')
    .replace(/#/g, '%23');
  return `url("data:image/svg+xml,${encoded}")`;
};

const generate = () => {
  const names = readdirSync(svgDir)
    .filter((f) => f.endsWith('.svg'))
    .map((f) => f.slice(0, -4))
    .sort();
  const shapes = Object.fromEntries(
    names.map((n) => [
      n,
      inner(readFileSync(join(svgDir, `${n}.svg`), 'utf8')),
    ]),
  );
  const mirrored = MIRRORED.filter((n) => names.includes(n));

  const data = [
    '// Generated by tools/icons.mjs from packages/icons/svg. Do not edit by hand.',
    '// Each value is the markup inside a 24 x 24 stroke icon (stroke: currentColor, width 2, round caps and joins).',
    '',
    ...names.map(
      (n) => `export const ${camel(n)}Icon = ${JSON.stringify(shapes[n])};`,
    ),
    '',
    '/** Every icon by name. Import a single `xIcon` instead if you want the smallest bundle. */',
    'export const ICONS = {',
    ...names.map((n) => `  ${JSON.stringify(n)}: ${camel(n)}Icon,`),
    '} as const;',
    '',
    'export type IconName = keyof typeof ICONS;',
    '',
    '/** Icons that point the way text runs. Flip them in right-to-left pages. */',
    `export const MIRRORED_ICONS: readonly IconName[] = ${JSON.stringify(mirrored)};`,
    '',
  ].join('\n');
  writeFileSync(join(pkg, 'src/data.ts'), data);

  // Words that describe each icon, for search boxes: ICON_TAGS['trash-2'] includes 'delete'.
  const allTags = JSON.parse(readFileSync(join(pkg, 'tags.json'), 'utf8'));
  const tagLines = names.map(
    (n) => `  ${JSON.stringify(n)}: ${JSON.stringify(allTags[n] ?? [])},`,
  );
  writeFileSync(
    join(pkg, 'src/tags.ts'),
    [
      '// Generated by tools/icons.mjs from packages/icons/tags.json. Do not edit by hand.',
      "import type { IconName } from './data.js';",
      '',
      "/** Words that describe each icon, for search boxes: ICON_TAGS['trash-2'] includes 'delete'. */",
      'export const ICON_TAGS: Record<IconName, readonly string[]> = {',
      ...tagLines,
      '};',
      '',
    ].join('\n'),
  );

  const css = [
    '/* Generated by tools/icons.mjs from packages/icons/svg. Do not edit by hand.',
    ' * <i class="ui-icon ui-icon-search"></i> draws the icon in the current text colour.',
    ' * Size and the right-to-left flip come from @lamsa-ui/css (.ui-icon, --ui-icon-size). */',
    '',
    '.ui-icon:not(svg, :has(> svg)) {',
    '  display: inline-block;',
    '  background-color: currentColor;',
    '  -webkit-mask: var(--ui-icon-mask) center / contain no-repeat;',
    '  mask: var(--ui-icon-mask) center / contain no-repeat;',
    '}',
    '',
    ...names.map(
      (n) => `.ui-icon-${n} {\n  --ui-icon-mask: ${maskUrl(shapes[n])};\n}\n`,
    ),
    mirrored.length
      ? `:is(${mirrored.map((n) => `.ui-icon-${n}`).join(', ')}):dir(rtl) {\n  transform: scaleX(-1);\n}\n`
      : '',
  ].join('\n');
  writeFileSync(join(pkg, 'icons.css'), css);
  console.log(
    `Generated ${names.length} icons (${mirrored.length} mirrored in RTL).`,
  );
};

const command = process.argv[2];
if (command === 'sync') sync();
else if (command === 'generate') generate();
else {
  console.error('Usage: node tools/icons.mjs sync | generate');
  process.exit(1);
}
